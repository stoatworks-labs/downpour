#include "Glyphs.h"

/**
    The built-in face, drawn.

    Twelve by twelve, '#' for ink, anything else for paper, **top row first**.
    `ParseArt` in Glyphs.cpp turns each one the right way up exactly once.

    ## Why these characters

    The katakana are the point. The falling code in the film is mirrored
    half-width katakana, and that is a *technique* rather than anything anyone
    owns -- but the well-known fan font that reproduces it is free for personal
    use only, so it is not something this repo can ship. These are drawn for
    this project and are MIT along with the rest of it.

    They are drawn **unmirrored**, at their real codepoints, and the Mirror
    Glyphs parameter flips them at sample time in the shader. Drawing them
    already-flipped would have saved a line of GLSL and made the atlas dump
    unreadable to anyone checking the shapes against a font, which is exactly
    the check that catches a badly drawn glyph.

    ## The metrics

    Latin and digits sit on an 8x9 body in columns 2..9, rows 1..9 -- a
    dot-matrix metric rather than a typeface one, because next to katakana a
    proportional-looking latin face reads as a mistake.

    Katakana use the full cell. They have to: they are built from three and four
    separate stroke groups and cramping them is what makes one indistinguishable
    from another at rain speed.

    ## Checking this file

    `dptest --atlas /tmp/atlas.png` draws every glyph. That is not a
    convenience, it is the only way this file is verifiable -- a katakana with a
    stroke in the wrong place still compiles, still renders, and still looks
    vaguely Japanese to anyone who is not reading it.
*/
